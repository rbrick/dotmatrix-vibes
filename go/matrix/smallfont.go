// SmallTextHeight is the height of the small font.
const SmallTextHeight = 5

// SmallTextWidth returns the width in pixels of s in the small font.
func SmallTextWidth(s string) int {
	n := len([]rune(s))
	return max(n*4-1, 0)
}

// DrawSmallText draws s in the 3x5 font with its top-left corner at (x, y)
// and returns the x coordinate just past it.
func (c *Canvas) DrawSmallText(x, y int, s string, col color.Color) int {
	for _, r := range strings.ToUpper(s) {
		if g, ok := smallFont[r]; ok {
			for gy, row := range g {
				for gx := range row {
					if row[gx] == '#' {
						c.Set(x+gx, y+gy, col)
					}
				}
			}
		}
		x += 4
	}
	return x
}
